import { NextRequest, NextResponse } from "next/server";
import { z } from "zod";
import { getSession } from "@/lib/auth";
import { prisma } from "@/lib/prisma";
import { interpretPrompt } from "@/lib/ollama";
import { checkRateLimit } from "@/lib/rate-limit";
import { parseBody, isApiError } from "@/lib/api-utils";
import { spawn } from "child_process";

const PROMPT_RATE_LIMIT = { name: "prompt", maxRequests: 5, windowSeconds: 3600 };

const promptSchema = z.object({
  prompt: z.string().min(1, "Le prompt ne peut pas etre vide").max(1000, "Max 1000 caracteres").transform((v) => v.trim()),
});

function triggerSync() {
  // Fast mode: collect articles without Ollama scoring (~30s instead of ~30min)
  // The hourly cron will score them later
  const child = spawn(
    "/opt/tech-veille/venv/bin/python3",
    ["/opt/tech-veille/main.py", "--fast"],
    {
      timeout: 300_000,
      stdio: "ignore",
      detached: false,
      env: {
        PATH: process.env.PATH || "/usr/bin:/bin",
        HOME: process.env.HOME || "/root",
        LANG: "en_US.UTF-8",
      } as unknown as NodeJS.ProcessEnv,
    },
  );
  child.on("close", (code) => {
    if (code !== 0) console.error(`[auto-sync] exited with code ${code}`);
    else console.log("[auto-sync] completed");
  });
  child.on("error", (err) => {
    console.error("[auto-sync] error:", err);
  });
}

function triggerRescore(userId: string) {
  const child = spawn(
    "/opt/tech-veille/venv/bin/python3",
    ["/opt/tech-veille/rescore.py", userId],
    {
      timeout: 600_000,
      stdio: "ignore",
      detached: false,
      env: {
        PATH: process.env.PATH || "/usr/bin:/bin",
        HOME: process.env.HOME || "/root",
        LANG: "en_US.UTF-8",
      } as unknown as NodeJS.ProcessEnv,
    },
  );
  child.on("close", (code) => {
    if (code !== 0) console.error(`[rescore] exited with code ${code}`);
    else console.log("[rescore] completed for user", userId);
  });
  child.on("error", (err) => {
    console.error("[rescore] error:", err);
  });
}

export async function POST(request: NextRequest) {
  const session = await getSession();
  if (!session) {
    return NextResponse.json({ error: "Non autorise" }, { status: 401 });
  }

  // Rate limiting per user
  const rl = checkRateLimit(session.userId, PROMPT_RATE_LIMIT);
  if (!rl.allowed) {
    return NextResponse.json(
      { error: "Trop de modifications. Reessaie plus tard." },
      { status: 429 }
    );
  }

  const data = await parseBody(request, promptSchema);
  if (isApiError(data)) return data;
  const prompt = data.prompt;

  try {
    const config = await interpretPrompt(prompt);

    // Preserve UI-only settings from previous config (not generated by LLM)
    const existingUser = await prisma.user.findUnique({
      where: { id: session.userId },
      select: { promptConfig: true },
    });
    const oldConfig = (existingUser?.promptConfig as Record<string, unknown>) || {};

    // Merge: LLM-generated fields + preserved UI fields
    const mergedConfig = {
      ...config,
      // Preserve user's source toggles (UI choice, not LLM)
      enabled_sources: oldConfig.enabled_sources || undefined,
      // Preserve user's followed accounts (UI choice, not LLM)
      followed_accounts: oldConfig.followed_accounts || undefined,
    };

    await prisma.user.update({
      where: { id: session.userId },
      data: {
        prompt,
        promptConfig: mergedConfig as object,
        scoringNotes: config.scoring_instructions,
      },
    });

    await prisma.promptHistory.create({
      data: {
        userId: session.userId,
        prompt,
        config: config as object,
      },
    });

    // Auto-trigger a sync so articles arrive immediately
    triggerSync();
    // Re-score existing articles in background with new preferences
    triggerRescore(session.userId);

    return NextResponse.json({ ok: true, config, syncTriggered: true, rescoreTriggered: true });
  } catch (err) {
    console.error("Prompt interpretation failed:", err);
    return NextResponse.json(
      { error: "Erreur lors de l'analyse du prompt" },
      { status: 500 }
    );
  }
}

"""Tests for official sources: Claude API release notes (one article per dated entry)."""

import sys
from datetime import datetime, timedelta, timezone
from unittest.mock import MagicMock, patch

sys.path.insert(0, "/opt/tech-veille")
from sources.release_notes import ReleaseNotesSource, parse_release_notes  # noqa: E402

TODAY = datetime(2026, 11, 6, 9, 0, tzinfo=timezone.utc)
HTML = """<html><body>
<h3>Cookie settings</h3><p>We use cookies.</p>
<h3 id="november-5-2026">November 5, 2026 \ue09a</h3>
<ul><li>You can now set up an IP allowlist for your organization in the Claude Console, in beta.</li>
<li>Requests from other IPs are rejected.</li></ul>
<h3 id="november-3-2026">November 3, 2026</h3>
<p>Text generated by Claude carries Anthropic's text watermark.</p>
<h3 id="october-1-2026">October 1, 2026</h3><ul><li>Old change.</li></ul>
</body></html>"""
PAGE = {"name": "API Claude", "url": "https://platform.claude.com/docs/en/release-notes/overview"}


def test_one_article_per_recent_dated_entry():
    arts = parse_release_notes(HTML.encode(), PAGE, cutoff=TODAY - timedelta(days=7))
    assert [a.title for a in arts] == ["Notes de version API Claude : 5 novembre 2026",
                                       "Notes de version API Claude : 3 novembre 2026"]
    first = arts[0]
    assert first.url == "https://platform.claude.com/docs/en/release-notes/overview#november-5-2026"
    assert first.platform == "release_notes" and first.is_official and first.category == "ia"
    # header line, then one line per change (the summarizer turns them into points)
    assert first.text.splitlines()[1:] == [
        "You can now set up an IP allowlist for your organization in the Claude Console, in beta.",
        "Requests from other IPs are rejected."]
    assert arts[1].text.splitlines()[1:] == ["Text generated by Claude carries Anthropic's text watermark."]


def test_ids_are_stable_between_runs():
    a = parse_release_notes(HTML.encode(), PAGE, cutoff=TODAY - timedelta(days=7))
    b = parse_release_notes(HTML.encode(), PAGE, cutoff=TODAY - timedelta(days=7))
    assert [x.external_id for x in a] == [x.external_id for x in b]


def test_failure_is_reported_for_health_alerts():
    src = ReleaseNotesSource(pages=[PAGE])
    with patch("sources.release_notes.net.get", side_effect=Exception("boom")):
        assert src.fetch() == []
    assert src.checks[0].ok is False and "API Claude" in src.checks[0].key


def test_working_page_is_reported_ok():
    src = ReleaseNotesSource(pages=[PAGE], max_age_days=3650)
    resp = MagicMock(content=HTML.encode())
    with patch("sources.release_notes.net.get", return_value=resp):
        assert len(src.fetch()) == 3
    assert src.checks[0].ok is True
